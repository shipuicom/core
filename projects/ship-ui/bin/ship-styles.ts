#!/usr/bin/env node
/**
 * Turns a `ship-styles.json` (the colours, variants and skins a project keeps) into the `@use` block of its styles.
 *
 *   ship-styles                                   # ./ship-styles.json → ./src/_ship-styles.scss
 *   ship-styles --in config/ship-styles.json --out src/styles/_ship.scss
 *   ship-styles --stdout                          # print instead of writing
 *
 * Then `@use 'ship-styles';` as the first line of styles.scss, in place of `@use '@ship-ui/core/styles'`.
 * The docs config editor exports the same JSON; a template scanner can later write it the way ship-fg writes the icon font.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  SHIP_STYLE_SKINS,
  shipStylesUse,
  type ShipStylesManifest,
} from '../src/lib/utilities/ship-styles';

const args = process.argv.slice(2);
const opt = (name: string, fallback: string) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1]! : fallback;
};

const input = resolve(opt('--in', 'ship-styles.json'));
const output = resolve(opt('--out', 'src/_ship-styles.scss'));

let manifest: ShipStylesManifest;
try {
  manifest = JSON.parse(readFileSync(input, 'utf8'));
} catch (e) {
  console.error(`ship-styles: cannot read ${input}: ${(e as Error).message}`);
  process.exit(1);
}

const unknown = Object.keys(manifest.skins ?? {}).filter(s => !(SHIP_STYLE_SKINS as readonly string[]).includes(s));
if (unknown.length) {
  console.error(`ship-styles: unknown skin(s) ${unknown.join(', ')}; known: ${SHIP_STYLE_SKINS.join(', ')}`);
  process.exit(1);
}

const scss = `// Generated by ship-styles from ${opt('--in', 'ship-styles.json')}; edit the JSON, not this file.\n${shipStylesUse(manifest)}\n`;

if (args.includes('--stdout')) process.stdout.write(scss);
else {
  writeFileSync(output, scss);
  console.log(`ship-styles: wrote ${output}`);
}
